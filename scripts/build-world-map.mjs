// One-off build-time data prep: projects Natural Earth's public-domain 110m land
// layer (via the world-atlas/topojson-client packages, devDependencies only — not
// shipped to the client) into a single static SVG path, baked into
// src/data/worldMap.ts. Run with `node scripts/build-world-map.mjs` after bumping
// the world-atlas version, if ever. Deliberately omits admin-0 country borders:
// this is the landmass/coastline layer only, matching the "no borders shown by
// default" requirement and keeping the map original rather than reused tile assets.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import * as topojson from 'topojson-client';
import landTopology from 'world-atlas/land-110m.json' with { type: 'json' };
import countriesTopology from 'world-atlas/countries-110m.json' with { type: 'json' };

const WIDTH = 1000;
const HEIGHT = 500;
const DECIMALS = 2;

function project([lng, lat]) {
  const x = ((lng + 180) / 360) * WIDTH;
  const y = ((90 - lat) / 180) * HEIGHT;
  return [round(x), round(y)];
}

function round(n) {
  return Math.round(n * 10 ** DECIMALS) / 10 ** DECIMALS;
}

function ringToPath(ring) {
  const points = ring.map(project);
  const [first, ...rest] = points;
  return `M${first[0]},${first[1]}L${rest.map(([x, y]) => `${x},${y}`).join('L')}Z`;
}

function polygonToPath(polygon) {
  return polygon.map(ringToPath).join('');
}

function geometryToPath(geometry) {
  if (geometry.type === 'Polygon') return polygonToPath(geometry.coordinates);
  if (geometry.type === 'MultiPolygon') {
    return geometry.coordinates.map(polygonToPath).join('');
  }
  throw new Error(`Unsupported geometry type: ${geometry.type}`);
}

function lineToPath(line) {
  const points = line.map(project);
  const [first, ...rest] = points;
  return `M${first[0]},${first[1]}L${rest.map(([x, y]) => `${x},${y}`).join('L')}`;
}

const landFeatures = topojson.feature(landTopology, landTopology.objects.land).features;
const landPath = landFeatures.map((f) => geometryToPath(f.geometry)).join('');

// Interior admin-0 boundaries only (shared edges between two different countries),
// via topojson.mesh's filter — this excludes coastlines, which the land layer
// above already draws. Rendered separately so it can be shown/hidden independent
// of the coastline silhouette (only revealed once the player zooms in), per the
// "no country borders shown by default" spec in geo-game-instructions.md.
const bordersMesh = topojson.mesh(
  countriesTopology,
  countriesTopology.objects.countries,
  (a, b) => a !== b,
);
const bordersPath = bordersMesh.coordinates.map(lineToPath).join('');

const output = `// Generated by scripts/build-world-map.mjs — do not edit by hand.
// Source: Natural Earth 110m land + admin-0 country layers (public domain, no
// attribution required), via the world-atlas npm package.
// Projection: equirectangular, viewBox is 0 0 ${WIDTH} ${HEIGHT} (lng -180..180 -> x 0..${WIDTH}, lat 90..-90 -> y 0..${HEIGHT}).
// This matches the lat/lng -> percentage projection used for pin placement in MapScope.tsx.

/** Landmass/coastline silhouette — always visible. */
export const WORLD_MAP_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}';
export const WORLD_MAP_PATH = '${landPath}';

/** Interior country border lines only (no coastline) — shown only once zoomed in. */
export const WORLD_BORDERS_PATH = '${bordersPath}';
`;

const outPath = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'data',
  'worldMap.ts',
);
writeFileSync(outPath, output);

console.log(
  `Wrote ${outPath} (${(output.length / 1024).toFixed(1)} KB, ${landFeatures[0].geometry.coordinates.length} landmasses, ${bordersMesh.coordinates.length} border segments)`,
);
